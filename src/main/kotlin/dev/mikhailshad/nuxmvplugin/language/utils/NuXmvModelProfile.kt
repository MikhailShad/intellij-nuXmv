/**
 * Kind of a model specification. Entries are ordered the way nuXmv numbers properties in its database.
 *
 * @property propertyType the type column printed by `show_property`
 */
enum class NuXmvSpecKind(val displayName: String, val propertyType: String) {
    CTL("CTL", "CTL"),
    COMPUTE("COMPUTE", "Quantitative"),
    LTL("LTL", "LTL"),
    PSL("PSL", "PSL"),
    INVAR("INVAR", "Invar");

    override fun toString(): String = displayName
}

/** Formula constructs that some checking algorithms do not support. */
enum class NuXmvSpecFeature(val description: String) {
    PAST("past temporal operators"),
    NEXT("next() inside the invariant"),
    RTCTL("bounded CTL operators"),
    BOUNDED("bounded LTL operators"),
    MACRO("specification is generated by a #FOR macro")
}

/**
 * One specification written in the model.
 *
 * @property module the module that declares the specification
 * @property instances paths of [module] instances reachable from `main`; `""` stands for `main` itself
 * @property context the module instance given with `IN`, if any
 * @property key a stable identifier used to store the specification in run configurations
 */
data class NuXmvSpecEntry(
    val kind: NuXmvSpecKind,
    val name: String?,
    val text: String,
    val module: String,
    val instances: List<String>,
    val context: String?,
    val features: Set<NuXmvSpecFeature>,
    val line: Int,
    val pointer: SmartPsiElementPointer<PsiElement>
) {
    val key: String
        get() = keyOf(kind, module, name, text)

    /** A short label for UI lists: the name if the specification has one, the formula otherwise. */
    val label: String
        get() = name ?: text

    companion object {
        fun keyOf(kind: NuXmvSpecKind, module: String, name: String?, text: String): String =
            if (name != null) "${kind.name}:$module:$name" else "${kind.name}:$module:#${normalizeFormula(text)}"

        /**
         * Brings a formula to a form that does not depend on spacing and parentheses,
         * so the text written in the model can be matched with the text printed by nuXmv.
         */
        fun normalizeFormula(text: String): String = text.filterNot { it.isWhitespace() || it == '(' || it == ')' }
    }
}

/**
 * What the run configuration needs to know about a model: its domain and its specifications.
 *
 * @property domainReason the declaration that determined [domain], for UI hints
 */
data class NuXmvModelProfile(
    val domain: NuXmvDomainType,
    val domainReason: String?,
    val hasFairness: Boolean,
    val specs: List<NuXmvSpecEntry>
) {
    fun specsOf(kind: NuXmvSpecKind): List<NuXmvSpecEntry> = specs.filter { it.kind == kind }

    fun findSpec(key: String): NuXmvSpecEntry? = specs.firstOrNull { it.key == key }

    /** The entry of the specification that contains [element], if any. */
    fun specAt(element: PsiElement): NuXmvSpecEntry? {
        val spec = PsiTreeUtil.getParentOfType(element, false, *SPEC_CLASSES) ?: return null
        return specs.firstOrNull { it.pointer.element == spec }
    }

    companion object {
        val EMPTY = NuXmvModelProfile(NuXmvDomainType.FINITE_DOMAIN, null, false, emptyList())

        /** Cached profile of [file]; must be called inside a read action. */
        fun of(file: NuXmvFile): NuXmvModelProfile =
            CachedValuesManager.getCachedValue(file) {
                CachedValueProvider.Result.create(build(file), PsiModificationTracker.MODIFICATION_COUNT)
            }

        private fun build(file: NuXmvFile): NuXmvModelProfile {
            val (domain, reason) = detectDomain(file)
            val modules = NuXmvScopes.modulesIn(file)
            val instances = instancePaths(modules)
            val pointers = SmartPointerManager.getInstance(file.project)
            val document = file.viewProvider.document
            val specs = modules.values.flatMap { module ->
                val moduleName = module.moduleDeclaration.moduleName?.name ?: return@flatMap emptyList()
                PsiTreeUtil.findChildrenOfAnyType(module, *SPEC_CLASSES).mapNotNull { spec ->
                    val kind = kindOf(spec) ?: return@mapNotNull null
                    NuXmvSpecEntry(
                        kind = kind,
                        name = PsiTreeUtil.getChildOfType(spec, NuXmvNamedSpecification::class.java)?.name,
                        text = formulaText(spec),
                        module = moduleName,
                        instances = instances[moduleName].orEmpty(),
                        context = PsiTreeUtil.getChildOfType(spec, NuXmvSpecContext::class.java)
                            ?.identifierUsage?.text,
                        features = featuresOf(spec),
                        line = (document?.getLineNumber(spec.textOffset) ?: 0) + 1,
                        pointer = pointers.createSmartPsiElementPointer(spec as PsiElement)
                    )
                }
            }
            val hasFairness = PsiTreeUtil.findChildrenOfAnyType(
                file,
                NuXmvFairnessConstraint::class.java,
                NuXmvJusticeConstraint::class.java,
                NuXmvCompassionConstraint::class.java
            ).isNotEmpty()
            return NuXmvModelProfile(domain, reason, hasFairness, specs)
        }

        val SPEC_CLASSES: Array<Class<out PsiElement>> = arrayOf(
            NuXmvCtlSpecification::class.java,
            NuXmvLtlSpecification::class.java,
            NuXmvInvarSpecification::class.java,
            NuXmvPslSpecification::class.java,
            NuXmvComputeSpecification::class.java
        )

        private fun kindOf(spec: PsiElement): NuXmvSpecKind? = when (spec) {
            is NuXmvCtlSpecification -> NuXmvSpecKind.CTL
            is NuXmvLtlSpecification -> NuXmvSpecKind.LTL
            is NuXmvInvarSpecification -> NuXmvSpecKind.INVAR
            is NuXmvPslSpecification -> NuXmvSpecKind.PSL
            is NuXmvComputeSpecification -> NuXmvSpecKind.COMPUTE
            else -> null
        }

        private fun formulaText(spec: PsiElement): String {
            val formula = when (spec) {
                is NuXmvPslSpecification -> spec.pslBody
                else -> PsiTreeUtil.getChildOfType(spec, NuXmvComputeExpr::class.java)
                    ?: PsiTreeUtil.getChildOfType(spec, NuXmvExpr::class.java)
            }
            return formula?.text?.replace(Regex("""\s+"""), " ")?.trim().orEmpty()
        }

        private fun featuresOf(spec: PsiElement): Set<NuXmvSpecFeature> {
            val features = mutableSetOf<NuXmvSpecFeature>()
            if (PsiTreeUtil.getParentOfType(spec, NuXmvForLoopMacro::class.java) != null) {
                features += NuXmvSpecFeature.MACRO
            }
            if (PsiTreeUtil.findChildOfType(spec, NuXmvBound::class.java) != null) {
                features += NuXmvSpecFeature.BOUNDED
            }
            PsiTreeUtil.processElements(spec) { element ->
                when (element.node.elementType) {
                    in PAST_TOKENS -> features += NuXmvSpecFeature.PAST
                    NuXmvTypes.NEXT_FUN -> features += NuXmvSpecFeature.NEXT
                    in RTCTL_TOKENS -> features += NuXmvSpecFeature.RTCTL
                }
                true
            }
            return features
        }

        private val PAST_TOKENS = setOf(
            NuXmvTypes.LTL_PREVIOUS,
            NuXmvTypes.LTL_NOT_PREVIOUS,
            NuXmvTypes.LTL_HISTORICALLY,
            NuXmvTypes.LTL_ONCE,
            NuXmvTypes.LTL_SINCE,
            NuXmvTypes.LTL_TRIGGERED,
            NuXmvTypes.LTL_TIMED_PREVIOUS,
            NuXmvTypes.LTL_AT_LAST
        )

        private val RTCTL_TOKENS = setOf(
            NuXmvTypes.RTCTL_EBF,
            NuXmvTypes.RTCTL_ABF,
            NuXmvTypes.RTCTL_EBG,
            NuXmvTypes.RTCTL_ABG,
            NuXmvTypes.RTCTL_BU
        )

        private fun detectDomain(file: NuXmvFile): Pair<NuXmvDomainType, String?> {
            if (file.isTimed) {
                return NuXmvDomainType.TIMED_DOMAIN to "@TIME_DOMAIN continuous"
            }
            PsiTreeUtil.findChildrenOfType(file, NuXmvSimpleTypeSpecifier::class.java).forEach { type ->
                val infinite = type.node.findChildByType(NuXmvTypes.INTEGER_TYPE)
                    ?: type.node.findChildByType(NuXmvTypes.REAL_TYPE)
                if (infinite != null) {
                    return NuXmvDomainType.INFINITE_DOMAIN to declarationHint(type, infinite.text)
                }
            }
            PsiTreeUtil.findChildOfType(file, NuXmvFunctionDeclaration::class.java)?.let { function ->
                return NuXmvDomainType.INFINITE_DOMAIN to "uninterpreted function at line ${lineOf(function)}"
            }
            return NuXmvDomainType.FINITE_DOMAIN to null
        }

        private fun declarationHint(type: PsiElement, typeName: String): String {
            val variable = PsiTreeUtil.getParentOfType(
                type,
                NuXmvSingleVarDeclaration::class.java,
                NuXmvSingleIvarDeclaration::class.java,
                NuXmvFunctionSpecification::class.java
            )
            val subject = variable?.text?.substringBefore(':')?.trim()
            return if (subject != null) "$subject : $typeName at line ${lineOf(type)}" else "$typeName at line ${
                lineOf(
                    type
                )
            }"
        }

        private fun lineOf(element: PsiElement): Int =
            (element.containingFile.viewProvider.document?.getLineNumber(element.textOffset) ?: 0) + 1

        private fun instancePaths(modules: Map<String, NuXmvModule>): Map<String, List<String>> {
            val paths = LinkedHashMap<String, MutableList<String>>()
            val main = modules[MAIN_MODULE] ?: return emptyMap()
            var budget = MAX_INSTANCE_PATHS

            fun record(module: NuXmvModule, path: String, stack: Set<String>) {
                val name = module.moduleDeclaration.moduleName?.name ?: return
                if (name in stack || budget-- <= 0) return
                paths.getOrPut(name) { mutableListOf() } += path
                module.isaModules().forEach { record(it, path, stack + name) }
            }

            fun visit(module: NuXmvModule, path: String, stack: Set<String>) {
                val name = module.moduleDeclaration.moduleName?.name ?: return
                if (name in stack || budget <= 0) return
                record(module, path, stack)
                for ((variable, type) in module.scope().submoduleEdges) {
                    val submodule = modules[type] ?: continue
                    visit(submodule, if (path.isEmpty()) variable else "$path.$variable", stack + name)
                }
            }

            visit(main, "", emptySet())
            return paths
        }

        private const val MAX_INSTANCE_PATHS = 10_000

        const val MAIN_MODULE = "main"
    }
}
