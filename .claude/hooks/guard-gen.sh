#!/bin/bash
input=$(cat)

targets=$(jq -r '.tool_input | (.file_path, .notebook_path, .pathInProject) // empty' <<<"$input")
patch=$(jq -r '.tool_input | (.input // .patch) // empty' <<<"$input")
if [[ -n "$patch" ]]; then
  targets+=$'\n'$(grep -E '^(\*\*\* (Add|Update|Delete) File:|\*\*\* Move to:|\+\+\+ |--- )' <<<"$patch")
fi

if grep -qE '(^|[[:space:]/])src/main/gen/' <<<"$targets"; then
  jq -n '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: "deny",
    permissionDecisionReason: "src/main/gen is regenerated by Gradle on every compile. Edit nuXmv.bnf / nuXmv.flex (or a mixin in language/psi/mixin) instead."}}'
fi

exit 0
